#!/usr/bin/env python3
"""Generates src/demoSeed.generated.ts from migrations/0011_seed_surgeon_demo.sql for POST /demo/reset.

Run from cloud/worker after gen_demo_seed.py:  python3 scripts/gen_demo_reset.py
D1 prepares one statement at a time, so the migration is split into single statements (comments dropped).
Times stay relative (strftime('now')), so a reset makes the demo look current again.
"""
import json, os, sqlite3

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "migrations", "0011_seed_surgeon_demo.sql")
OUT = os.path.join(ROOT, "src", "demoSeed.generated.ts")

statements, buf = [], ""
for line in open(SRC, encoding="utf-8").read().splitlines():
    if not buf and (not line.strip() or line.lstrip().startswith("--")):
        continue
    buf += line + "\n"
    if sqlite3.complete_statement(buf):
        statements.append(buf.strip().rstrip(";").strip())
        buf = ""
if buf.strip():
    raise SystemExit("0011 ends with an incomplete statement")

with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("// GENERATED by scripts/gen_demo_reset.py from migrations/0011_seed_surgeon_demo.sql. Do not edit.\n")
    fh.write("// One SQL statement per entry; POST /demo/reset replays them after clearing the demo crew.\n")
    fh.write("export const DEMO_SEED_SQL: readonly string[] = ")
    fh.write(json.dumps(statements, ensure_ascii=False, indent=0))
    fh.write(";\n")
print(f"wrote {OUT}: {len(statements)} statements, {os.path.getsize(OUT)//1024} KB")
