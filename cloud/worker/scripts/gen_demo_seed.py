#!/usr/bin/env python3
"""Generates migrations/0011_seed_surgeon_demo.sql: FAKE data for Demo Astronaut and Demo Flight Surgeon.

Run from cloud/worker:  python3 scripts/gen_demo_seed.py   (then python3 scripts/gen_demo_reset.py for POST /demo/reset)
Deterministic (fixed random seed). All timestamps are relative to strftime('now') at apply time, so the
dashboards look current whenever the migration is applied. Every row uses the fixed demo UUIDs
(00000000-0000-4000-8000-00000000d0xx) or a 'demo-' client id, so queries/delete_user.sql removes it.
Values follow the original features/web-app mock data (src/data/*.ts): Ryan Vega "Nova", Expedition 74,
mission day 142 of 180, sleep stages, mood dip, radiation with a solar particle event, bone loss, immune panel.
"""
import json, math, random, sqlite3, glob, os

random.seed(74)
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "migrations", "0011_seed_surgeon_demo.sql")

def uid(n): return f"00000000-0000-4000-8000-00000000d{n:03d}"
VEGA, ORTIZ = uid(1), uid(2)

def ago(minutes):
    minutes = int(round(minutes))
    return f"strftime('%Y-%m-%dT%H:%M:%fZ','now','-{minutes} minutes')" if minutes > 0 else "strftime('%Y-%m-%dT%H:%M:%fZ','now')"
def day_ago(d): return f"date('now','-{d} days')" if d else "date('now')"

def q(v):
    if v is None: return "NULL"
    if isinstance(v, Raw): return v.s
    if isinstance(v, bool): return "1" if v else "0"
    if isinstance(v, (int, float)): return repr(round(v, 4)) if isinstance(v, float) else str(v)
    return "'" + str(v).replace("'", "''") + "'"
class Raw:
    def __init__(self, s): self.s = s
def T(minutes): return Raw(ago(minutes))

# Metric thresholds from the real metric_definitions (built by applying the migrations in memory).
mem = sqlite3.connect(":memory:")
for f in sorted(glob.glob(os.path.join(ROOT, "migrations", "*.sql"))):
    base = os.path.basename(f)
    if base.startswith(("0008", "0011")): continue
    mem.executescript(open(f).read())
METRICS = {r[0]: r for r in mem.execute(
    "SELECT metric, unit, green_min, green_max, yellow_min, yellow_max FROM metric_definitions")}
def _inside(v, lo, hi): return (lo is None or v >= lo) and (hi is None or v <= hi)
def level(metric, v):  # same rule as levelFromThresholds in src/health.ts
    _, _, gl, gh, yl, yh = METRICS[metric]
    if _inside(v, gl, gh): return "green"
    if _inside(v, yl, yh): return "yellow"
    return "red"

sql = []
def insert(table, cols, rows, verb="INSERT OR IGNORE", chunk=150):
    for i in range(0, len(rows), chunk):
        body = ",\n".join("(" + ",".join(q(v) for v in r) + ")" for r in rows[i:i + chunk])
        sql.append(f"{verb} INTO {table} ({','.join(cols)}) VALUES\n{body};")

