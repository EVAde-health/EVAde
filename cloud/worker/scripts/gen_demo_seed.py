def insert(table, cols, rows, verb="INSERT OR IGNORE", chunk=150):
    for i in range(0, len(rows), chunk):
        body = ",\n".join("(" + ",".join(q(v) for v in r) + ")" for r in rows[i:i + chunk])
        sql.append(f"{verb} INTO {table} ({','.join(cols)}) VALUES\n{body};")

