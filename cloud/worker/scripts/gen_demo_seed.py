def _inside(v, lo, hi): return (lo is None or v >= lo) and (hi is None or v <= hi)
def level(metric, v):  # same rule as levelFromThresholds in src/health.ts
    _, _, gl, gh, yl, yh = METRICS[metric]
    if _inside(v, gl, gh): return "green"
    if _inside(v, yl, yh): return "yellow"
    return "red"

