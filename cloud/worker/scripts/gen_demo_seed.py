def ago(minutes):
    minutes = int(round(minutes))
    return f"strftime('%Y-%m-%dT%H:%M:%fZ','now','-{minutes} minutes')" if minutes > 0 else "strftime('%Y-%m-%dT%H:%M:%fZ','now')"
def day_ago(d): return f"date('now','-{d} days')" if d else "date('now')"

def q(v):
    if v is None: return "NULL"
    if isinstance(v, Raw): return v.s
    if isinstance(v, bool): return "1" if v else "0"
    if isinstance(v, (int, float)): return repr(round(v, 4)) if isinstance(v, float) else str(v)
    return "'" + str(v).replace("'", "''") + "'"
class Raw:
    def __init__(self, s): self.s = s
def T(minutes): return Raw(ago(minutes))

