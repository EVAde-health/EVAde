# ---------------------------------------------------------------- vitals / observations
obs = []
def ob(user, short, metric, i, value, minutes, device="demo"):
    unit = METRICS[metric][1]
    obs.append((f"demo-{short}-{metric}-{i}", user, metric, round(value, 2), unit, T(minutes), "synthetic", device, level(metric, value)))

PROFILES = {
    "vega":         dict(hr=68, sbp=117, dbp=76, spo2=97.6, temp=37.05, rr=14, glu=94, hrv=48, sleep=6.9),
    "steady":       dict(hr=62, sbp=112, dbp=72, spo2=98.0, temp=36.9,  rr=13, glu=90, hrv=58, sleep=7.6),
    "tachy":        dict(hr=88, sbp=121, dbp=79, spo2=97.0, temp=37.2,  rr=16, glu=98, hrv=34, sleep=6.6),
    "hypertensive": dict(hr=74, sbp=138, dbp=89, spo2=97.4, temp=36.95, rr=15, glu=101, hrv=41, sleep=7.0),
    "poor_sleep":   dict(hr=71, sbp=118, dbp=77, spo2=97.5, temp=37.0,  rr=14, glu=95, hrv=39, sleep=5.4),
    "quiet":        dict(hr=65, sbp=115, dbp=74, spo2=97.8, temp=36.9,  rr=13, glu=92, hrv=52, sleep=7.3),
}
MIN_DAY = 24 * 60
for n, _, _, _, prof in CREW:
    user, short, P = uid(n), f"d{n:03d}", PROFILES[prof]
    days = 30 if n == 1 else 14
    step_h = 3 if n == 1 else 6
    i = 0
    for h in range(days * 24 - 1, -1, -step_h):
        minutes = h * 60 + 25
        circ = math.sin((24 - (h % 24)) / 24 * 2 * math.pi)
        i += 1
        hr = P["hr"] + 5 * circ + random.gauss(0, 2.5)
        if n == 1 and h == 3: hr = 104            # morning spike after a short night (shows yellow)
        if prof == "tachy" and h < 30: hr += 14     # Reyes trending up over the last day
        ob(user, short, "heart_rate", i, hr, minutes, "Astroskin")
        ob(user, short, "systolic_bp", i, P["sbp"] + 3 * circ + random.gauss(0, 3) + (6 if prof == "hypertensive" and h < 48 else 0), minutes, "BP cuff")
        ob(user, short, "diastolic_bp", i, P["dbp"] + 2 * circ + random.gauss(0, 2), minutes, "BP cuff")
        ob(user, short, "spo2", i, min(100, P["spo2"] + random.gauss(0, 0.5)), minutes, "Astroskin")
        ob(user, short, "body_temp", i, P["temp"] + 0.25 * circ + random.gauss(0, 0.08), minutes, "Thermolab")
        ob(user, short, "respiration_rate", i, P["rr"] + random.gauss(0, 1), minutes, "Astroskin")
        if n == 1 or h % 12 == 0:
            ob(user, short, "blood_glucose", i, P["glu"] + 12 * max(0, circ) + random.gauss(0, 4), minutes, "CGM")
            ob(user, short, "stress_index", i, max(5, min(95, 38 + 12 * circ + random.gauss(0, 6) + (15 if prof == "tachy" else 0))), minutes)
    for d in range(days):
        m = d * MIN_DAY + 6 * 60
        dip = 1.3 if n == 1 and 8 <= d <= 14 else 0   # the isolation dip from the original mock data
        ob(user, short, "hrv_rmssd", d, P["hrv"] + random.gauss(0, 5) - 6 * dip, m)
        sleep = max(3.8, min(9.2, P["sleep"] + random.gauss(0, 0.6) - 0.6 * dip - (1.2 if n == 1 and d == 0 else 0)))
        ob(user, short, "sleep_hours", d, sleep, m - 60, "Actiwatch")
        if n == 1 or d < 7:
            deep, rem = sleep * random.uniform(0.17, 0.23), sleep * random.uniform(0.2, 0.26)
            awake = random.uniform(0.2, 0.6)
            ob(user, short, "sleep_deep_hours", d, deep, m - 60, "Actiwatch")
            ob(user, short, "sleep_rem_hours", d, rem, m - 60, "Actiwatch")
            ob(user, short, "sleep_light_hours", d, sleep - deep - rem, m - 60, "Actiwatch")
            ob(user, short, "sleep_awake_hours", d, awake, m - 60, "Actiwatch")
        mood = max(1, min(5, round(3.8 - dip + random.gauss(0, 0.5) - (1 if prof == "poor_sleep" else 0))))
        ob(user, short, "mood", d, mood, m + 600)
        ob(user, short, "stress", d, max(1, min(5, round(2.4 + dip + random.gauss(0, 0.6) + (1 if prof == "tachy" else 0)))), m + 600)
        ob(user, short, "daily_radiation_msv", d, (2.4 if n == 1 and d == 24 else random.uniform(0.52, 0.70)), m + 900, "Dosimeter")
        ob(user, short, "health_score", d, max(40, min(98, 82 - 8 * dip + random.gauss(0, 3) - (10 if prof in ("tachy", "poor_sleep") else 0))), m + 960)
        ob(user, short, "ecg_irregular_pct", d, max(0, random.gauss(0.6, 0.3) + (1.4 if prof == "tachy" else 0)), m + 30, "ECG patch")
        if n == 1:
            ob(user, short, "eeg_drowsiness_z", d, random.gauss(0.2 + 0.5 * dip, 0.3), m + 120)
            for axis, (a, b) in {"focus": (72, 78), "energy": (61, 70), "calm": (58, 66), "social": (49, 64), "cognition": (81, 80), "motivation": (70, 74)}.items():
                ob(user, short, f"behavior_{axis}", d, max(20, min(100, a + (b - a) * (d / days) + random.gauss(0, 3) - 6 * dip)), m + 700)
            ob(user, short, "behavior_index", d, max(20, min(100, 66 - 7 * dip + random.gauss(0, 3))), m + 700)
    weeks = 20 if n == 1 else 6
    for w in range(weeks):
        m = w * 7 * MIN_DAY + 9 * 60
        loss = -0.28 * (weeks - w)
        ob(user, short, "bone_hip_change_pct", w, loss + random.gauss(0, 0.08), m, "Ultrasound")
        ob(user, short, "bone_spine_change_pct", w, loss * 0.9 + random.gauss(0, 0.08), m, "Ultrasound")
        ob(user, short, "bone_density_change_pct", w, loss * 0.95, m, "Ultrasound")
        ob(user, short, "body_mass_change_pct", w, -0.12 * (weeks - w) + random.gauss(0, 0.1), m)
    for k, (wbc, lym, il6, crp, ebv) in enumerate([(5.1, 1.1, 6.8, 1.9, 2), (5.6, 1.4, 4.2, 1.2, 1), (6.0, 1.6, 3.1, 0.9, 1)]):
        m = (k * 14 + 2) * MIN_DAY
